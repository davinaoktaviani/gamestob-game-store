const productsGrid = document.getElementById("productsGrid");
const searchInput = document.getElementById("searchInput");
const genreFilter = document.getElementById("genreFilter");
const platformFilter = document.getElementById("platformFilter");
const sortPrice = document.getElementById("sortPrice");
const resultCount = document.getElementById("resultCount");

const params = new URLSearchParams(window.location.search);
const category = params.get("category");

/* BUILD A SINGLE PRODUCT CARD */

function createProductCard(game) {

    const card = document.createElement("div");
    card.className = "product-card";

    const img = document.createElement("img");
    img.src = game.image;
    img.alt = game.title;
    img.loading = "lazy";
    attachImageFallback(img, game.title, game.genre);
    card.appendChild(img);

    const content = document.createElement("div");
    content.className = "product-content";

    const h3 = document.createElement("h3");
    h3.textContent = game.title;
    content.appendChild(h3);

    const genreP = document.createElement("p");
    genreP.className = "genre";
    genreP.textContent = game.genre;
    content.appendChild(genreP);

    const platformSpan = document.createElement("span");
    platformSpan.className = "platform";
    platformSpan.textContent = game.platform;
    content.appendChild(platformSpan);

    const cardBottom = document.createElement("div");
    cardBottom.className = "card-bottom";

    const priceDiv = document.createElement("div");
    priceDiv.className = "price";
    priceDiv.textContent = "Rp " + game.price.toLocaleString("id-ID");
    cardBottom.appendChild(priceDiv);

    const wishlistBtn = document.createElement("button");
    wishlistBtn.className = "wishlist";
    wishlistBtn.textContent = "♥";
    wishlistBtn.setAttribute("aria-label", "Add to wishlist");
    cardBottom.appendChild(wishlistBtn);

    content.appendChild(cardBottom);

    const buyLink = document.createElement("a");
    buyLink.href = `purchase.html?game=${encodeURIComponent(game.title)}`;
    buyLink.className = "buy-btn";
    buyLink.textContent = "Buy Now";
    content.appendChild(buyLink);

    card.appendChild(content);

    return card;
}

function renderProducts(data) {

    productsGrid.innerHTML = "";
    resultCount.textContent = `${data.length} Games Found`;

    if (data.length === 0) {

        const empty = document.createElement("p");
        empty.className = "empty-state";
        empty.textContent = "No games match your filters. Try adjusting your search.";
        productsGrid.appendChild(empty);
        return;

    }

    data.forEach(game => {
        productsGrid.appendChild(createProductCard(game));
    });

}

function applyFilters() {

    let filtered = [...games];

    const keyword = searchInput.value.toLowerCase();
    const genre = genreFilter.value;
    const platform = platformFilter.value;

    if (category) {
        filtered = filtered.filter(game => game.category === category);
    }

    if (keyword !== "") {
        filtered = filtered.filter(game =>
            game.title.toLowerCase().includes(keyword)
        );
    }

    if (genre !== "all") {
        filtered = filtered.filter(game => game.genre === genre);
    }

    if (platform !== "all") {
        filtered = filtered.filter(game => game.platform === platform);
    }

    if (sortPrice.value === "low") {
        filtered.sort((a, b) => a.price - b.price);
    }

    if (sortPrice.value === "high") {
        filtered.sort((a, b) => b.price - a.price);
    }

    renderProducts(filtered);

}

searchInput.addEventListener("keyup", applyFilters);
genreFilter.addEventListener("change", applyFilters);
platformFilter.addEventListener("change", applyFilters);
sortPrice.addEventListener("change", applyFilters);

document.addEventListener("click", function (e) {

    if (e.target.classList.contains("wishlist")) {
        e.target.classList.toggle("liked");
    }

});

applyFilters();
